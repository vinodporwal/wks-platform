def _parse_num(s):
    """Parse '3,569.98' -> 3569.98"""
    return float(s.replace(",", ""))

# ── Parse raw data and build JSON structure ────────────────────────────────
gt_curves = {}   # {asset_name: [{load_mw, heat_rate, free_steam_factor}, ...]}
hrsg_curves = {}  # {asset_name: [{load_tph, heat_rate, free_steam_factor}, ...]}

errors = []
for line_num, line in enumerate(RAW_DATA.strip().split("\n"), 1):
    parts = line.split("\t")
    if len(parts) != 8:
        errors.append(f"Line {line_num}: expected 8 fields, got {len(parts)}: {line[:80]}")
        continue
    mandt, site, equiptype, cpputility, gtload, heatrate, freestm, tagging = parts
    load = _parse_num(gtload)
    hr = _parse_num(heatrate)
    fsf = _parse_num(freestm)

    if tagging in GT_TAGGING_TO_NAME:
        name = GT_TAGGING_TO_NAME[tagging]
        gt_curves.setdefault(name, []).append({
            "load_mw": load,
            "heat_rate_kcal_kwh": hr,
            "free_steam_factor": fsf,
        })
    elif tagging in HRSG_TAGGING_TO_NAME:
        name = HRSG_TAGGING_TO_NAME[tagging]
        hrsg_curves.setdefault(name, []).append({
            "load_tph": load,
            "heat_rate_btu_lb": hr,
            "free_steam_factor": fsf,
        })
    else:
        errors.append(f"Line {line_num}: unknown tagging '{tagging}'")

if errors:
    print("ERRORS:")
    for e in errors:
        print(f"  {e}")
    raise SystemExit(1)

# Sort each curve by load
